  function autoAchievementsText(ctx) {
    var lines = [];
    var completedMilestones = ctx.activities.filter(function (a) { return a.activity_type === "milestone" && a.status === "complete"; });
    if (completedMilestones.length) {
      lines.push("Completed milestones: " + completedMilestones.map(function (a) { return a.name; }).join(", ") + ".");
    }
    var completedActivities = ctx.activities
      .filter(function (a) { return a.activity_type !== "milestone" && a.status === "complete"; })
      .sort(function (a, b) { return (b.duration || 0) - (a.duration || 0); })
      .slice(0, 5);
    if (completedActivities.length) {
      lines.push("Completed activities: " + completedActivities.map(function (a) { return a.name; }).join(", ") + ".");
    }
    if (lines.length === 0) return "No completed milestones or activities recorded yet.";
    return lines.join(" ");
  }

