  function healthGaugeSvg(score, rag) {
    var size = 160;
    var r = 64;
    var cx = size / 2;
    var cy = size / 2 + 10;
    var circumference = Math.PI * r; // half circle
    var svg = svgEl("svg", { width: size, height: size / 2 + 30, viewBox: "0 0 " + size + " " + (size / 2 + 30) });
    svg.appendChild(
      svgEl("path", {
        d: "M " + (cx - r) + " " + cy + " A " + r + " " + r + " 0 0 1 " + (cx + r) + " " + cy,
        fill: "none", stroke: "var(--divider)", "stroke-width": 16, "stroke-linecap": "round",
      })
    );
    if (score != null) {
      var frac = score / 100;
      var dash = frac * circumference;
      svg.appendChild(
        svgEl("path", {
          d: "M " + (cx - r) + " " + cy + " A " + r + " " + r + " 0 0 1 " + (cx + r) + " " + cy,
          fill: "none", stroke: "var(" + RAG_COLOR_VAR[rag] + ")", "stroke-width": 16, "stroke-linecap": "round",
          "stroke-dasharray": dash + " " + (circumference - dash),
        })
      );
    }
    var text = svgEl("text", { x: cx, y: cy - 6, "font-size": 28, "font-weight": "700", "text-anchor": "middle", fill: "var(--text-primary)" });
    text.textContent = score == null ? "—" : String(score);
    svg.appendChild(text);
    return svg;
  }

