  /** Central place every "View" / management-action link goes through, since the same
   * cross-page navigation pattern (set the target page's own filter state, then
   * router.go) is already used throughout this app (Portfolio's Details panel,
   * Meetings' hub links). */
  function navigateToLink(link) {
    if (!link || !link.module) return;
    if (link.module === "risks" && window.PCC.risks) {
      if (link.recordId && window.PCC.risks.expandRisk) window.PCC.risks.expandRisk(link.recordId);
    } else if (link.module === "rfis" && window.PCC.rfis) {
      if (link.recordId && window.PCC.rfis.expandRfi) window.PCC.rfis.expandRfi(link.recordId);
    } else if (link.module === "meetings" && window.PCC.meetings) {
      if (link.recordId && window.PCC.meetings.expandMeeting) window.PCC.meetings.expandMeeting(link.recordId);
    } else if (link.module === "changeOrders" && window.PCC.changeOrders) {
      if (uiState.projectId && window.PCC.changeOrders.filterByProject) window.PCC.changeOrders.filterByProject(uiState.projectId);
    } else if (link.module === "cost" && window.PCC.cost) {
      // cost.js's filterByProject() always lands on its Budget tab (no public API to
      // pick EVM/Summary directly) — acceptable here since the project filter still
      // gets the user to the right place; they switch tabs themselves from there.
      window.PCC.cost.filterByProject(uiState.projectId);
    }
    window.PCC.router.go(link.module);
  }

