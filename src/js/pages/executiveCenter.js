  function autoStatusText(ctx) {
    var p = ctx.project;
    var lines = [];
    lines.push((p.name || "This project") + " is currently " + (p.status || "on_track").replace("_", " ") + ", " + fmtPct(p.progress) + " complete overall.");
    if (ctx.totalActivityCount > 0) {
      lines.push(
        "Schedule progress is " + fmtPct(ctx.scheduleProgressPct) + " against a planned finish of " + (ctx.plannedFinish || "not set") + "." +
        (ctx.forecastFinish
          ? " Forecast finish is " + ctx.forecastFinish + (ctx.forecastVarianceDays ? " (" + (ctx.forecastVarianceDays > 0 ? "+" : "") + ctx.forecastVarianceDays + " day(s) vs plan)" : ", on plan") + "."
          : "")
      );
    }
    if (ctx.costSummary.budgeted > 0) {
      lines.push("Cost: " + fmtMoney(ctx.costSummary.actual, p.currency) + " actual against a " + fmtMoney(ctx.costSummary.budgeted, p.currency) + " budget.");
    }
    return lines.join(" ");
  }

  function autoAchievementsText(ctx) {
    var lines = [];
    var completedMilestones = ctx.activities.filter(function (a) { return a.activity_type === "milestone" && a.status === "complete"; });
    if (completedMilestones.length) {
      lines.push("Completed milestones: " + completedMilestones.map(function (a) { return a.name; }).join(", ") + ".");
    }
    var completedActivities = ctx.activities
      .filter(function (a) { return a.activity_type !== "milestone" && a.status === "complete"; })
      .sort(function (a, b) { return (b.duration || 0) - (a.duration || 0); })
      .slice(0, 5);
    if (completedActivities.length) {
      lines.push("Completed activities: " + completedActivities.map(function (a) { return a.name; }).join(", ") + ".");
    }
    if (lines.length === 0) return "No completed milestones or activities recorded yet.";
    return lines.join(" ");
  }

