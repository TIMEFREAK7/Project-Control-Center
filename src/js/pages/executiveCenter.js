  /** Planned progress S-curve, from real activity dates — a full cumulative-% curve
   * over time. As of Gate 25 (Advanced Schedule Performance), `snapshots` — captured
   * Schedule Performance snapshots (store.js's schedule_performance_snapshots,
   * newest-first) — supplies the first real "actual progress on date X" history PCC
   * has ever stored, so an actual overlay can finally be drawn as a real curve instead
   * of a single today-only point. Snapshots outside the planned curve's own date range
   * are skipped rather than distorting the shared x-axis; with zero snapshots the chart
   * falls back to planned-only, same as before this gate. */
  function sCurveChart(card, activities, referenceDate, todayIso, snapshots) {
    var dated = activities.filter(function (a) { return a.planned_start && a.planned_finish; });
    if (dated.length === 0) return noDataNote(card, "No activities with planned dates yet.");
    var diffDays = window.PCC.scheduleGanttLayout.diffDays;
    var addDays = window.PCC.scheduleGanttLayout.addDays;
    var rangeStart = dated.reduce(function (min, a) { return a.planned_start < min ? a.planned_start : min; }, dated[0].planned_start);
    var rangeEnd = dated.reduce(function (max, a) { return a.planned_finish > max ? a.planned_finish : max; }, dated[0].planned_finish);
    var totalWeight = dated.reduce(function (s, a) { return s + (a.duration || diffDays(a.planned_start, a.planned_finish) || 1); }, 0);
    if (totalWeight <= 0) return noDataNote(card);

    var totalSpan = Math.max(1, diffDays(rangeStart, rangeEnd));
    var steps = Math.min(40, totalSpan);
    var points = [];
    for (var s = 0; s <= steps; s++) {
      var day = addDays(rangeStart, Math.round((s / steps) * totalSpan));
      var cum = 0;
      dated.forEach(function (a) {
        var dur = a.duration || diffDays(a.planned_start, a.planned_finish) || 1;
        var frac;
        if (day <= a.planned_start) frac = 0;
        else if (day >= a.planned_finish) frac = 1;
        else frac = diffDays(a.planned_start, day) / (diffDays(a.planned_start, a.planned_finish) || 1);
        cum += dur * frac;
      });
      points.push({ day: day, pct: (cum / totalWeight) * 100 });
    }

    var width = 480;
    var height = 200;
    var padL = 34;
    var padB = 20;
    var plotW = width - padL - 10;
    var plotH = height - padB - 10;
    function xFor(day) { return padL + (diffDays(rangeStart, day) / totalSpan) * plotW; }
    function yFor(pct) { return 10 + plotH - (pct / 100) * plotH; }

    var svg = svgEl("svg", { width: width, height: height, style: "display:block;max-width:100%;" });
    [0, 25, 50, 75, 100].forEach(function (pct) {
      var y = yFor(pct);
      svg.appendChild(svgEl("line", { x1: padL, y1: y, x2: width - 10, y2: y, stroke: "var(--grid-line)", "stroke-width": 1 }));
      var t = svgEl("text", { x: 2, y: y + 3, "font-size": 9, fill: "var(--text-secondary)" });
      t.textContent = pct + "%";
      svg.appendChild(t);
    });

    var pathD = points.map(function (p, i) { return (i === 0 ? "M " : "L ") + xFor(p.day) + " " + yFor(p.pct); }).join(" ");
    svg.appendChild(svgEl("path", { d: pathD, fill: "none", stroke: "var(--status-info)", "stroke-width": 2 }));

    if (referenceDate >= rangeStart && referenceDate <= rangeEnd) {
      var refX = xFor(referenceDate);
      svg.appendChild(svgEl("line", { x1: refX, y1: 10, x2: refX, y2: 10 + plotH, stroke: "var(--signal-amber)", "stroke-width": 1.5, "stroke-dasharray": "3,3" }));
    }

    // Gate 25: actual-progress overlay from captured Schedule Performance snapshots —
    // the only "actual progress on date X" history this app has ever stored.
    var actualPoints = (snapshots || [])
      .filter(function (sn) { return sn.schedule_progress_pct != null && sn.captured_at.slice(0, 10) >= rangeStart && sn.captured_at.slice(0, 10) <= rangeEnd; })
      .map(function (sn) { return { day: sn.captured_at.slice(0, 10), pct: sn.schedule_progress_pct }; })
      .sort(function (a, b) { return a.day < b.day ? -1 : a.day > b.day ? 1 : 0; });

    if (actualPoints.length > 0) {
      var actualPathD = actualPoints.map(function (ap, i) { return (i === 0 ? "M " : "L ") + xFor(ap.day) + " " + yFor(ap.pct); }).join(" ");
      svg.appendChild(svgEl("path", { d: actualPathD, fill: "none", stroke: "var(--status-on-track)", "stroke-width": 2 }));
      actualPoints.forEach(function (ap) {
        svg.appendChild(svgEl("circle", { cx: xFor(ap.day), cy: yFor(ap.pct), r: 3, fill: "var(--status-on-track)" }));
      });
    }

    card.appendChild(svg);
    var legend = document.createElement("p");
    legend.className = "text-secondary";
    legend.style.fontSize = "var(--text-xs)";
    legend.style.marginTop = "var(--space-1)";
    legend.textContent =
      actualPoints.length > 0
        ? "Planned cumulative progress (blue), duration-weighted across " + dated.length + " dated activity(ies), vs. actual progress (green) from " +
          actualPoints.length + " captured Schedule Performance snapshot(s). Dashed line: data date."
        : "Planned cumulative progress, duration-weighted across " + dated.length + " dated activity(ies). Dashed line: data date. " +
          "Capture a Schedule Performance snapshot (below) to start plotting actual progress here.";
    card.appendChild(legend);
  }

  function floatDistributionBuckets(activities) {
    var buckets = [
      { label: "< 0 (over)", test: function (f) { return f < 0; }, color: "var(--status-critical)" },
      { label: "0 (critical)", test: function (f) { return f === 0; }, color: "var(--status-critical)" },
      { label: "1–5", test: function (f) { return f >= 1 && f <= 5; }, color: "var(--status-at-risk)" },
      { label: "6–15", test: function (f) { return f >= 6 && f <= 15; }, color: "var(--status-info)" },
      { label: "16+", test: function (f) { return f >= 16; }, color: "var(--status-on-track)" },
    ];
    var withFloat = activities.filter(function (a) { return a.total_float != null; });
    return buckets.map(function (b) {
      return { label: b.label, color: b.color, value: withFloat.filter(function (a) { return b.test(a.total_float); }).length };
    });
  }

